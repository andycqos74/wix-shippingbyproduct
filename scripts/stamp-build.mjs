// Writes src/lib/build-info.ts so the UI can show exactly which code is running.
// Runs automatically before dev, build, release and typecheck (npm "pre" scripts).
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

function git(cmd) {
  try {
    return execSync(`git ${cmd}`, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

const commit = git('rev-parse --short HEAD') || 'unknown';
const dirty = git('status --porcelain --untracked-files=no -- src') ? '+changes' : '';
const builtAt = new Date().toISOString();

writeFileSync(
  new URL('../src/lib/build-info.ts', import.meta.url),
  `// Generated by scripts/stamp-build.mjs. Do not edit.\nexport const BUILD = { commit: '${commit}${dirty}', builtAt: '${builtAt}' };\n`,
);
console.log(`build stamp: ${commit}${dirty} @ ${builtAt}`);
